// Local dev builds pass nothing here and keep hitting whatever HttpClientFactory.*.kt already
// falls back to (emulator loopback / LAN IP on Android, localhost on iOS). Passing
// -PapiBaseUrl=<hosted backend URL> — or setting the API_BASE_URL env var, which Xcode's build
// phase forwards as this same property — points either platform at a real hosted backend
// instead, without changing anyone's local workflow.
abstract class GenerateApiBaseUrlOverride : DefaultTask() {
    @get:Input
    abstract val apiBaseUrl: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val file = outputDir.get().file("com/boundless/template/core/network/ApiBaseUrlOverride.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            package com.boundless.template.core.network

            // Generated by :core:network's build.gradle.kts — do not edit by hand.
            internal const val API_BASE_URL_OVERRIDE: String = "${apiBaseUrl.get()}"

            """.trimIndent(),
        )
    }
}

val generateApiBaseUrlOverride =
    tasks.register<GenerateApiBaseUrlOverride>("generateApiBaseUrlOverride") {
        apiBaseUrl.set((findProperty("apiBaseUrl") as String?).orEmpty())
        outputDir.set(layout.buildDirectory.dir("generated/apiBaseUrl/kotlin"))
    }

